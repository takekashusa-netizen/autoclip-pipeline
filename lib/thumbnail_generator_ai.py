#!/usr/local/bin/python3
"""
lib/thumbnail_generator_ai.py

Real, automated GtaxZombies-style thumbnail generator.
Uses DALL-E 3 to generate AI art matching the exact brand style,
then ImageMagick to add text overlays and branding.
Wired into --auto-queue so every new clip gets a real thumbnail.
"""
import base64
import json
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Character roster mapped to game/content type
CHARACTER_MAP = {
    "apex": ["Wraith", "Octane", "Bloodhound", "Caustic", "Lifeline", "Bangalore"],
    "warzone": ["operator in tactical gear", "masked soldier", "spec ops character"],
    "nba2k": ["basketball player in MyCareer mode", "NBA player in arena"],
    "fc": ["soccer player celebrating", "footballer in stadium"],
    "default": ["gaming character in tactical gear"],
}

# Color schemes per moment type
COLOR_MAP = {
    "CLUTCH":     ("purple lightning", "purple and gold", "Wraith"),
    "WIN":        ("golden light explosion", "gold and yellow", "Octane"),
    "HYPE":       ("electric green energy", "neon green", "Octane"),
    "RAGE":       ("red fire explosion", "red and orange", "Bangalore"),
    "FUNNY":      ("colorful chaos", "yellow and white", "Caustic"),
    "GAS":        ("toxic green gas clouds", "toxic green", "Caustic"),
    "RING":       ("orange storm wall", "orange and red", "Lifeline"),
    "STANDOFF":   ("dramatic face-off lighting", "green and black", "Octane"),
    "SQUAD":      ("battle scene chaos", "purple and orange", "Bloodhound"),
    "DEFAULT":    ("dramatic dark battlefield", "purple and gold", "Wraith"),
}


def detect_moment_type(title):
    t = title.upper()
    if "CLUTCH" in t: return "CLUTCH"
    if "GAS" in t or "CAUSTIC" in t: return "GAS"
    if "RING" in t: return "RING"
    if "STANDOFF" in t or "1V1" in t or "1V3" in t: return "STANDOFF"
    if "WIN" in t or "CHAMPION" in t or "VICTORY" in t: return "WIN"
    if "RAGE" in t or "MESSED" in t or "FUCKED" in t: return "RAGE"
    if "SQUAD" in t or "COME GET" in t: return "SQUAD"
    if "HYPE" in t or "INSANE" in t or "CRAZY" in t: return "HYPE"
    if "FUNNY" in t or "LOL" in t: return "FUNNY"
    return "DEFAULT"


# Real display label per detected game — used to be hardcoded to "Apex
# Legends" everywhere below regardless of what `game` was actually passed
# in, so a Warzone or NBA 2K clip still got branded as Apex. Fixed
# 2026-09-15 so the prompt (and the text overlay, see add_text_overlay)
# actually reflect the real game for that job.
GAME_LABELS = {
    "apex": "Apex Legends", "apex legends": "Apex Legends",
    "warzone": "Call of Duty: Warzone", "call of duty": "Call of Duty",
    "nba2k": "NBA 2K", "nba 2k": "NBA 2K",
    "fc": "EA Sports FC", "fifa": "EA Sports FC",
    "arc raiders": "ARC Raiders",
    "valorant": "Valorant", "fortnite": "Fortnite", "minecraft": "Minecraft",
    "default": "GtaxZombies",
}


def _game_label(game):
    return GAME_LABELS.get((game or "default").lower(), (game or "GtaxZombies").title())


def build_dalle_prompt(title, transcript_excerpt, game="apex"):
    moment = detect_moment_type(title)
    bg_effect, colors, _ = COLOR_MAP.get(moment, COLOR_MAP["DEFAULT"])
    roster = CHARACTER_MAP.get((game or "default").lower(), CHARACTER_MAP["default"])
    character = roster[0]
    label = _game_label(game)

    # Extract key moment text for the image (max 2 lines)
    words = title.replace('"', '').replace("'", "").split()
    key_words = " ".join(words[:6])

    prompt = f"""Dark cinematic YouTube gaming thumbnail, 1792x1024 pixels, 16:9 ratio.

RIGHT SIDE (50% of frame): {character}, hyper-realistic render, 
intense combat-ready expression, dramatic pose facing left toward text, 
{bg_effect} surrounding them, detailed armor/skin visible.

LEFT SIDE (50% of frame): Completely clear dark area for text overlay, 
deep shadow gradient from left edge, no characters or objects blocking text space.

BACKGROUND: Dark cinematic {label} battlefield/arena, {colors} color palette, 
atmospheric particle effects, dramatic depth, epic scale.

BOTTOM LEFT corner: Clear dark space for "GtaxZombies" logo text.
BOTTOM CENTER: Clear space for a {label} ranked/rank badge graphic.
TOP LEFT corner: Small clear space for "{label.upper()}" text.

Style: Same as professional gaming YouTube thumbnails. Ultra-detailed, 
cinematic lighting, no UI elements, no text generated by AI (text will be added separately).
No watermarks. Professional gaming thumbnail quality."""

    return prompt


def generate_thumbnail_dalle(title, transcript_excerpt, output_path, game="apex"):
    """Real DALL-E 3 call — generates the background art, then adds text via ImageMagick."""
    import openai

    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        raise RuntimeError("OPENAI_API_KEY not set")

    client = openai.OpenAI(api_key=api_key)
    prompt = build_dalle_prompt(title, transcript_excerpt, game)

    print(f"  [thumbnail] calling DALL-E 3...")
    response = client.images.generate(
        model="gpt-image-2.5-flare",
        prompt=prompt,
        size="1536x1024",
        n=1,
    )

    img_url = response.data[0].url
    raw_path = output_path.replace(".jpg", "_raw.jpg")
    import urllib.request
    urllib.request.urlretrieve(img_url, raw_path)

    # Apply text overlay with ImageMagick
    final_path = add_text_overlay(raw_path, title, output_path, game)
    if os.path.exists(raw_path):
        os.remove(raw_path)

    return final_path


def add_text_overlay(bg_path, title, output_path, game="apex"):
    """Real ImageMagick text overlay matching GtaxZombies brand style."""

    # parse title into 2-3 bold lines
    clean = re.sub(r'["\']', '', title)
    clean = re.sub(r'\|.*', '', clean).strip()
    parts = clean.split(' - ')
    line1 = parts[0][:30].upper() if len(parts) > 1 else clean[:22].upper()
    line2 = parts[1][:28].upper() if len(parts) > 1 else clean[22:44].upper()

    # font path — use system font
    font_path = "/System/Library/AssetsV2/com_apple_MobileAsset_Font7/7722fac06d2ccff23ed22b9ab921460b835e3e8c.asset/AssetData/K2D.ttc"
    if not os.path.exists(font_path):
        font_path = "/System/Library/Fonts/Supplemental/Verdana Bold.ttf"

    cmd = [
        "convert", bg_path,
        "-resize", "1280x720^",
        "-gravity", "center",
        "-extent", "1280x720",

        # dark gradient on left side for text readability
        "(",
        "-size", "640x720",
        "gradient:black-none",
        "-channel", "Alpha",
        "-evaluate", "multiply", "0.75",
        "+channel",
        ")",
        "-gravity", "West",
        "-composite",

        # line 1 — white
        "-font", font_path,
        "-pointsize", "72",
        "-fill", "white",
        "-stroke", "black",
        "-strokewidth", "3",
        "-gravity", "NorthWest",
        "-annotate", "+40+80", line1,

        # line 2 — yellow/gold
        "-fill", "#FFD700",
        "-stroke", "black",
        "-strokewidth", "3",
        "-pointsize", "80",
        "-gravity", "NorthWest",
        "-annotate", "+40+170", line2,

        # GtaxZombies brand bottom left
        "-fill", "white",
        "-stroke", "black",
        "-strokewidth", "2",
        "-pointsize", "42",
        "-font", font_path,
        "-gravity", "SouthWest",
        "-annotate", "+40+30", "GtaxZombies",

        # game label top left — was hardcoded to "APEX\nLEGENDS" regardless
        # of which game this clip is actually from; now uses the real
        # detected game (see determine_video_game / GAME_LABELS)
        "-fill", "white",
        "-stroke", "black",
        "-strokewidth", "1",
        "-pointsize", "22",
        "-gravity", "NorthWest",
        "-annotate", "+40+30", _game_label(game).upper().replace(" ", "\n", 1),

        output_path
    ]

    result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        # fallback — just resize without overlay
        subprocess.run(["convert", bg_path, "-resize", "1280x720^",
                        "-gravity", "center", "-extent", "1280x720", output_path],
                       capture_output=True, timeout=30)

    return output_path


def generate_and_upload_thumbnail(video_id, title, transcript_excerpt,
                                   youtube_creds=None, game="apex"):
    """
    Full pipeline: generate thumbnail → upload to YouTube.
    Call this after a clip is processed and uploaded.
    """
    thumb_dir = os.path.join(ROOT, "thumbnails", "ai_generated")
    os.makedirs(thumb_dir, exist_ok=True)

    safe_name = re.sub(r'[^a-z0-9]', '_', title.lower())[:40]
    output_path = os.path.join(thumb_dir, f"{safe_name}.jpg")

    try:
        generate_thumbnail_dalle(title, transcript_excerpt, output_path, game)
        print(f"  [thumbnail] generated: {output_path}")
    except Exception as e:
        print(f"  [thumbnail] DALL-E failed: {e}")
        return None

    # upload to YouTube if credentials provided
    if youtube_creds and video_id:
        try:
            from googleapiclient.discovery import build
            from googleapiclient.http import MediaFileUpload
            youtube = build("youtube", "v3", credentials=youtube_creds)
            youtube.thumbnails().set(
                videoId=video_id,
                media_body=MediaFileUpload(output_path, mimetype="image/jpeg")
            ).execute()
            print(f"  [thumbnail] uploaded to YouTube video {video_id}")
        except Exception as e:
            print(f"  [thumbnail] YouTube upload failed: {e}")

    return output_path


